def probe_video_duration(path):
    try:
        return float(command_output([
            "ffprobe",
            "-v", "error",
            "-show_entries", "format=duration",
            "-of", "default=noprint_wrappers=1:nokey=1",
            str(path),
        ]))
    except Exception:
        return 0.0


def prepare_clip(input_file, output_file, duration):
    source_duration = probe_video_duration(input_file)

    if source_duration <= duration + 0.2:
        start_time = 0.0
    else:
        max_start = max(0.0, source_duration - duration - 0.1)
        start_time = random.uniform(0, max_start)

    zoom = random.uniform(1.03, 1.10)
    pan_x = random.choice(["left", "right", "center"])
    pan_y = random.choice(["top", "bottom", "center"])

    # Overscale first, then crop with a tiny animated movement.
    base_w = int(VIDEO_WIDTH * zoom)
    base_h = int(VIDEO_HEIGHT * zoom)
    if pan_x == "left":
        x_expr = "0"
    elif pan_x == "right":
        x_expr = f"iw-{VIDEO_WIDTH}"
    else:
        x_expr = f"(iw-{VIDEO_WIDTH})/2"
    if pan_y == "top":
        y_expr = "0"
    elif pan_y == "bottom":
        y_expr = f"ih-{VIDEO_HEIGHT}"
    else:
        y_expr = f"(ih-{VIDEO_HEIGHT})/2"

    video_filter = (
        f"scale={base_w}:{base_h}:force_original_aspect_ratio=increase:flags=lanczos,"
        f"crop={VIDEO_WIDTH}:{VIDEO_HEIGHT}:"
        f"x='{x_expr}':y='{y_expr}',"
        "setsar=1,setdar=9/16,fps=30"
    )

    command = [
        "ffmpeg", "-y",
        "-ss", f"{start_time:.3f}",
        "-i", str(input_file),
        "-t", f"{duration:.3f}",
        "-vf", video_filter,
        "-an",
        "-r", str(FPS),
        "-c:v", "libx264",
        "-preset", "medium",
        "-crf", "17",
        "-pix_fmt", "yuv420p",
        "-movflags", "+faststart",
        str(output_file),
    ]
    run_command(command)


def create_concat_file(clips):
    concat_file = WORK_DIR / "concat.txt"

    with open(concat_file, "w", encoding="utf-8") as file:
        for clip in clips:
            path = clip.resolve()
            path_string = str(path).replace("'", "'\\''")
            file.write(f"file '{path_string}'\n")

    return concat_file


