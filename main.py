def search_pexels(query, page=1):
    url = "https://api.pexels.com/v1/videos/search"

    headers = {"Authorization": PEXELS_API_KEY}

    params = {
        "query": query,
        "orientation": "portrait",
        "size": "large",
        "per_page": 80,
        "page": page,
        "locale": "en-US",
    }

    response = requests.get(
        url,
        headers=headers,
        params=params,
        timeout=30,
    )
    response.raise_for_status()

    return response.json().get("videos", [])


def choose_video_file(video):
    files = video.get("video_files", [])
    vertical = []

    for item in files:
        width = item.get("width") or 0
        height = item.get("height") or 0
        link = item.get("link")
        if not link:
            continue
        if height > width and width >= 540 and height >= 960:
            vertical.append(item)

    if vertical:
        return max(
            vertical,
            key=lambda item: (
                (item.get("width") or 0) * (item.get("height") or 0),
                item.get("fps") or 0,
            ),
        )

    usable = [
        item for item in files
        if item.get("link") and (item.get("width") or 0) >= 720
    ]
    if usable:
        return max(
            usable,
            key=lambda item: (
                (item.get("width") or 0) * (item.get("height") or 0),
                item.get("fps") or 0,
            ),
        )

    return None


def select_unique_videos(topic, used_clips):
    search_queries = [topic["search"]] + topic.get("fallback_searches", [])
    candidates = {}

    for query in search_queries:
        print(f"Searching Pexels: {query}")

        for page in range(1, 4):
            try:
                videos = search_pexels(query, page)
            except Exception as error:
                print("Pexels search error:", error)
                continue

            for video in videos:
                video_id = str(video.get("id", ""))
                if not video_id or video_id in used_clips:
                    continue

                video_file = choose_video_file(video)
                if not video_file:
                    continue

                candidates[video_id] = {
                    "id": video_id,
                    "link": video_file["link"],
                }

            if len(candidates) >= 35:
                break

        if len(candidates) >= NUMBER_OF_CLIPS:
            break

    candidates_list = list(candidates.values())
    random.shuffle(candidates_list)

    if len(candidates_list) < NUMBER_OF_CLIPS:
        raise RuntimeError(
            f"Not enough NEW Pexels clips. Found {len(candidates_list)}, "
            f"need {NUMBER_OF_CLIPS}."
        )

    selected = candidates_list[:NUMBER_OF_CLIPS]

    print("Selected NEW Pexels IDs:")
    for item in selected:
        print(" ", item["id"])

    return selected


def download_video(url, destination):
    print(f"Downloading: {destination}")

    response = requests.get(
        url,
        stream=True,
        timeout=120,
        headers={"User-Agent": "Mozilla/5.0"},
    )
    response.raise_for_status()

    with open(destination, "wb") as file:
        for chunk in response.iter_content(chunk_size=1024 * 1024):
            if chunk:
                file.write(chunk)


