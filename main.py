def create_final_video(silent_video, text, boundaries=None):
    audio_duration = get_audio_duration()
    print(f"Audio duration: {audio_duration:.2f}s")

    silent_duration = probe_video_duration(silent_video)
    if silent_duration < audio_duration:
        extra = audio_duration - silent_duration + 0.25
        print(f"Extending visual track by {extra:.2f}s")
        extended = WORK_DIR / "silent_extended.mp4"
        command = [
            "ffmpeg", "-y",
            "-stream_loop", "-1",
            "-i", str(silent_video),
            "-t", f"{audio_duration + 0.25:.3f}",
            "-c:v", "libx264",
            "-preset", "medium",
            "-crf", "17",
            "-pix_fmt", "yuv420p",
            "-r", str(FPS),
            str(extended),
        ]
        run_command(command)
        silent_video = extended

    create_subtitle_file(text, audio_duration, boundaries=boundaries)

    audio_filter = (
        "highpass=f=70,"
        "lowpass=f=14000,"
        "acompressor=threshold=-18dB:ratio=2:attack=15:release=120,"
        "loudnorm=I=-15:TP=-1.5:LRA=8"
    )

    subtitle_path = SUBTITLE_FILE.resolve().as_posix().replace(":", r"\:")
    subtitle_filter = f"ass='{subtitle_path}'"

    final_command = [
        "ffmpeg", "-y",
        "-i", str(silent_video),
        "-i", str(VOICE_FILE),
        "-map", "0:v:0",
        "-map", "1:a:0",
        "-vf", subtitle_filter,
        "-af", audio_filter,
        "-c:v", "libx264",
        "-preset", "slow",
        "-crf", "17",
        "-profile:v", "high",
        "-level", "4.2",
        "-pix_fmt", "yuv420p",
        "-c:a", "aac",
        "-b:a", "192k",
        "-ar", "48000",
        "-shortest",
        "-movflags", "+faststart",
        str(OUTPUT_VIDEO),
    ]

    run_command(final_command)

    if not OUTPUT_VIDEO.exists() or OUTPUT_VIDEO.stat().st_size < 10000:
        raise RuntimeError("Final video was not created correctly.")

    print(f"Final video created: {OUTPUT_VIDEO}")


